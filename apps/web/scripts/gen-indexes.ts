type ListSpec = {
  /** Facade file name without `.ts`. */
  file: string;
  /** Exported constant name. */
  exportName: string;
  /** What a registered item is called in messages. */
  what: string;
  /** Property holding the key; null for a record keyed by property name. */
  keyProp: string | null;
  /** Bare string elements are allowed (permissions, noPiiTables). */
  strings?: boolean;
  /** Extra literal properties to read. */
  extras?: string[];
  /** Key format check. */
  pattern?: RegExp;
};

const SPECS = {
  jobs: { file: "jobs", exportName: "jobs", what: "job", keyProp: "kind" },
  webhooks: { file: "jobs", exportName: "webhookHandlers", what: "webhook handler", keyProp: "provider" },
  schedules: { file: "schedules", exportName: "schedules", what: "schedule", keyProp: "kind" },
  events: { file: "events", exportName: "events", what: "event", keyProp: "kind" },
  permissions: { file: "permissions", exportName: "permissions", what: "permission", keyProp: "permission", strings: true },
  nav: { file: "nav", exportName: "nav", what: "nav item", keyProp: "key", extras: ["area"] },
  settings: { file: "config", exportName: "settings", what: "setting", keyProp: "key", pattern: /^[a-z_]+$/ },
  flags: { file: "config", exportName: "flags", what: "flag", keyProp: "key", pattern: /^ff_[a-z]+_[a-z0-9_]+$/ },
  noPii: { file: "privacy", exportName: "noPiiTables", what: "no-PII table", keyProp: null, strings: true },
  mergeFields: { file: "merge-fields", exportName: "mergeFields", what: "merge field", keyProp: null },
} satisfies Record<string, ListSpec>;

type SpecName = keyof typeof SPECS;

/** Reads one list or record export; returns null when the file or export is absent. */
function readList(reader: Reader, module: string, spec: ListSpec): Entry[] | null {
  const init = reader.exported(spec.exportName);
  if (!init) return null;
  const { src } = reader;
  const out: Entry[] = [];
  const add = (node: ts.Node, index: number, key: string, extra: Entry["extra"] = {}) => {
    if (spec.pattern && !spec.pattern.test(key)) reader.problem(node, `${spec.what} key "${key}" does not match ${spec.pattern}`);
    out.push({ module, rel: src.rel, line: lineOf(src, node), index, key, extra });
  };

  // Records keyed by property name (mergeFields) and string lists (noPiiTables).
  if (spec.keyProp === null && !spec.strings) {
    if (!ts.isObjectLiteralExpression(init)) {
      reader.problem(init, `\`${spec.exportName}\` must be an object literal keyed by ${spec.what} name`);
      return out;
    }
    init.properties.forEach((p, i) => {
      const name = p.name ? propName(p.name) : null;
      if (ts.isSpreadAssignment(p) || name === null) {
        reader.problem(p, `registry values must be string literals (${spec.what} names in \`${spec.exportName}\`)`);
        return;
      }
      add(p, i, name);
    });
    return out;
  }

  if (!ts.isArrayLiteralExpression(init)) {
    reader.problem(init, `\`${spec.exportName}\` must be an array literal`);
    return out;
  }
  init.elements.forEach((el, i) => {
    if (ts.isSpreadElement(el)) {
      reader.problem(el, `spread entries are not allowed in \`${spec.exportName}\`; list each ${spec.what} with its literal key`);
      return;
    }
    const value = unwrap(el);
    if (isStringish(value)) {
      if (spec.strings) add(el, i, value.text);
      else reader.problem(el, `${spec.what} entries must be objects, not strings`);
      return;
    }
    if (spec.keyProp === null) {
      reader.problem(el, `registry values must be string literals (\`${spec.exportName}\`)`);
      return;
    }
    const obj = reader.objectOf(value, spec.what);
    if (!obj) return;
    const key = reader.literal(obj, spec.keyProp, spec.what);
    if (key === null) return;
    const extra: Entry["extra"] = {};
    for (const name of spec.extras ?? []) {
      const v = reader.literal(obj, name, `${spec.what} "${key}"`);
      if (v !== null) extra[name] = v;
    }
    add(el, i, key, extra);
  });
  return out;
}

/** Reads a single-object export (`privacy`, `seed`); returns null when absent. */
function readSingle(reader: Reader, exportName: string, what: string, withAfter: boolean): { after: string[] } | null {
  const init = reader.exported(exportName);
  if (!init) return null;
  const obj = reader.objectOf(init, what);
  if (!obj) return { after: [] };
  return { after: withAfter ? reader.literalArray(obj, "after", what) : [] };
}

/** Fails on a key declared twice, naming both files. */
function checkDuplicates(entries: Entry[], what: string, problems: string[]): void {
  const seen = new Map<string, Entry>();
  for (const e of entries) {
    const first = seen.get(e.key);
    if (first) problems.push(`duplicate ${what} "${e.key}" in ${first.rel}:${first.line} and ${e.rel}:${e.line}`);
    else seen.set(e.key, e);
  }
}

const byKey = (a: { key: string }, b: { key: string }) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
const sortStrings = (xs: Iterable<string>) => [...new Set(xs)].sort();
const q = (s: string) => JSON.stringify(s);
/** A safe identifier for an import alias. */
const ident = (...parts: string[]) => parts.map((p) => p.replace(/[^A-Za-z0-9]/g, "_")).join("_");

function listDirs(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith(".") && !d.name.startsWith("_"))
    .map((d) => d.name)
    .sort();
}

function listFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => d.name)
    .sort();
}

/** Topological order of `{ module, after }` (ties by module id); `after` of an absent module is ignored. */
export function topoSort(
  items: { module: string; after: string[] }[],
  what: string,
  problems: string[],
): { module: string; after: string[] }[] {
  const present = new Map(items.map((i) => [i.module, i]));
  const known = new Set<string>([...MODULE_IDS, ...present.keys()]);
  for (const i of items) {
    for (const a of i.after) if (!known.has(a)) problems.push(`${what} of "${i.module}" runs after unknown module "${a}"`);
  }
  const done: { module: string; after: string[] }[] = [];
  const placed = new Set<string>();
  let remaining = [...items].sort((a, b) => (a.module < b.module ? -1 : 1));
  while (remaining.length) {
    const ready = remaining.find((i) => i.after.every((a) => placed.has(a) || !present.has(a)));
    if (!ready) {
      problems.push(`${what} order has a cycle among: ${remaining.map((r) => r.module).join(", ")}`);
      return done;
    }
    done.push(ready);
    placed.add(ready.module);
    remaining = remaining.filter((r) => r !== ready);
  }
  return done;
}

