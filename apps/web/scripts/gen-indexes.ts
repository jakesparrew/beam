/** Builds every output in memory. Throws GenIndexesError listing every problem. */
export function generate(root: string): Record<string, string> {
  const problems: string[] = [];
  const modules = listDirs(path.join(root, MODULES_DIR));
  for (const m of modules) {
    if (!/^[a-z][a-z0-9]*$/.test(m)) problems.push(`${MODULES_DIR}/${m}: module ids are lower-case letters and digits`);
  }

  const lists = Object.fromEntries(Object.keys(SPECS).map((k) => [k, [] as Entry[]])) as Record<SpecName, Entry[]>;
  const privacyModules: string[] = [];
  const demoSeeds: { module: string; after: string[] }[] = [];

  for (const m of modules) {
    const readers = new Map<string, Reader | null>();
    const reader = (facade: string): Reader | null => {
      if (!readers.has(facade)) {
        const rel = `${MODULES_DIR}/${m}/${facade}.ts`;
        readers.set(facade, fs.existsSync(path.join(root, rel)) ? new Reader(readSource(root, rel)) : null);
      }
      return readers.get(facade) ?? null;
    };
    for (const [name, spec] of Object.entries(SPECS) as [SpecName, ListSpec][]) {
      const r = reader(spec.file);
      const found = r ? readList(r, m, spec) : null;
      if (found) lists[name].push(...found);
    }
    const privacy = reader("privacy");
    if (privacy && readSingle(privacy, "privacy", "privacy registration", false)) privacyModules.push(m);
    const seedReader = reader("seed");
    const seed = seedReader ? readSingle(seedReader, "seed", "demo seed", true) : null;
    if (seed) demoSeeds.push({ module: m, after: seed.after });
    for (const r of readers.values()) if (r) problems.push(...r.problems);
  }

  // Merge fields are keyed `<m>.<field>`.
  for (const e of lists.mergeFields) {
    e.extra.field = e.key;
    e.key = `${e.module}.${e.key}`;
  }
  for (const name of Object.keys(SPECS) as SpecName[]) {
    if (name !== "noPii") checkDuplicates(lists[name], SPECS[name].what, problems);
  }
  for (const e of lists.nav) {
    if (e.extra.area !== "admin" && e.extra.area !== "portal") {
      problems.push(`${e.rel}:${e.line}: nav item "${e.key}" has area "${String(e.extra.area)}"; use "admin" or "portal"`);
    }
  }

  const templates = collectTemplates(root, problems);
  const schema = collectSchema(root);
  const dbSeeds = collectDbSeeds(root, problems);
  const messages = collectMessages(root);
  const demoOrder = topoSort(demoSeeds, "demo seed", problems);
  const defaultOrder = topoSort(dbSeeds, "default seed", problems);

  if (problems.length) throw new GenIndexesError(problems);

  const out: Record<string, string> = {};
  out[OUTPUTS.jobs] = keyedFile(lists.jobs, SPECS.jobs, "JOB_BY_KIND", "JOBS");
  out[OUTPUTS.webhooks] = keyedFile(lists.webhooks, SPECS.webhooks, "WEBHOOK_HANDLERS", null);
  out[OUTPUTS.schedules] = keyedFile(lists.schedules, SPECS.schedules, "SCHEDULE_BY_KIND", "SCHEDULES");
  out[OUTPUTS.events] = keyedFile(lists.events, SPECS.events, "EVENTS", null);
  out[OUTPUTS.settings] = keyedFile(lists.settings, SPECS.settings, "SETTINGS", null, (e) => `{ ...${at(e, "settings")}, owner: ${q(e.module)} }`);
  out[OUTPUTS.flags] = keyedFile(lists.flags, SPECS.flags, "FLAGS", null, (e) => `{ ...${at(e, "flags")}, owner: ${q(e.module)} }`);
  out[OUTPUTS.mergeFields] = keyedFile(
    lists.mergeFields,
    SPECS.mergeFields,
    "MERGE_FIELDS",
    null,
    (e) => `${ident(e.module, "mergeFields")}[${q(String(e.extra.field))}]!`,
  );

  const perms = [...lists.permissions].sort(byKey);
  out[OUTPUTS.permissions] = file(!perms.length, [], [
    ...(perms.length ? ["export const PERMISSIONS = [", ...perms.map((p) => `  ${q(p.key)},`), "] as const;"] : ["export const PERMISSIONS = [] as const;"]),
    "",
    ...objectLiteral("PERMISSION_MODULE", perms.map((p) => [p.key, q(p.module)])),
  ]);

  const nav = [...lists.nav].sort(byKey);
  const navArea = (area: string) => nav.filter((e) => e.extra.area === area).map((e) => `    ${at(e, "nav")},`);
  out[OUTPUTS.nav] = file(!nav.length, moduleImports(nav, "nav", "nav"), [
    ...objectLiteral("NAV_BY_KEY", nav.map((e) => [e.key, at(e, "nav")])),
    "",
    "export const NAV = {",
    "  admin: [",
    ...navArea("admin"),
    "  ],",
    "  portal: [",
    ...navArea("portal"),
    "  ],",
    "} as const;",
  ]);

  const noPii = sortStrings(lists.noPii.map((e) => e.key));
  out[OUTPUTS.privacy] = file(
    !privacyModules.length && !noPii.length,
    sortStrings(privacyModules).map((m) => `import { privacy as ${ident(m, "privacy")} } from ${q(`../modules/${m}/privacy`)};`),
    [
      ...objectLiteral("GDPR_REGISTRY", privacyModules.map((m) => [m, ident(m, "privacy")])),
      "",
      noPii.length ? `export const NO_PII_TABLES = [${noPii.map(q).join(", ")}] as const;` : "export const NO_PII_TABLES = [] as const;",
    ],
  );

  out[OUTPUTS.seeds] = seedFile("DEMO_SEEDS", demoOrder, (m) => `../modules/${m}/seed`);
  out[OUTPUTS.dbSeeds] = seedFile("DEFAULT_SEEDS", defaultOrder, (m) => `./${m}`);
  out[OUTPUTS.templates] = templatesFile(templates);
  out[OUTPUTS.schema] = file(!schema.length, [], schema.map((s) => `export * from ${q(`./${s}`)};`));
  out[OUTPUTS.messages] = messagesFile(messages);

  out[OUTPUTS.types] = file(false, [], [
    ...union("ModuleId", modules),
    ...union("JobKind", sortStrings(lists.jobs.map((e) => e.key))),
    ...union("EventKind", sortStrings(lists.events.map((e) => e.key))),
    ...union("Permission", sortStrings(perms.map((e) => e.key))),
    ...union("ScheduleKind", sortStrings(lists.schedules.map((e) => e.key))),
    ...union("SettingKey", sortStrings(lists.settings.map((e) => e.key))),
    ...union("FlagKey", sortStrings(lists.flags.map((e) => e.key))),
    ...union("TemplateKey", sortStrings(templates.map((e) => e.key))),
    ...union("MergeFieldKey", sortStrings(lists.mergeFields.map((e) => e.key))),
    ...union("WebhookHandlerProvider", sortStrings(lists.webhooks.map((e) => e.key))),
    ...union("NavKey", sortStrings(nav.map((e) => e.key))),
    "/** Catalogue keys are `<module>.<screen>.<element>`; the catalogues are too large for a literal union. */",
    "export type MessageKey = `${ModuleId}.${string}`;",
  ]);
  return out;
}

function seedFile(name: string, order: { module: string; after: string[] }[], from: (m: string) => string): string {
  const imports = sortStrings(order.map((s) => s.module)).map((m) => `import { seed as ${ident(m, "seed")} } from ${q(from(m))};`);
  const rows = order.map(
    (s) => `  { module: ${q(s.module)}, after: [${s.after.map(q).join(", ")}], run: ${ident(s.module, "seed")}.run },`,
  );
  const body = rows.length ? [`export const ${name} = [`, ...rows, "] as const;"] : [`export const ${name} = [] as const;`];
  return file(!order.length, imports, body);
}

/** `packages/email/src/templates/<folder>/index.ts` exporting `templates`, keyed `<folder>.<name>`. */
function collectTemplates(root: string, problems: string[]): Entry[] {
  const entries: Entry[] = [];
  for (const folder of listDirs(path.join(root, TEMPLATES_DIR))) {
    const rel = `${TEMPLATES_DIR}/${folder}/index.ts`;
    if (!fs.existsSync(path.join(root, rel))) continue;
    const reader = new Reader(readSource(root, rel));
    const init = reader.exported("templates");
    if (init && !ts.isArrayLiteralExpression(init)) reader.problem(init, "`templates` must be an array literal");
    if (init && ts.isArrayLiteralExpression(init)) {
      init.elements.forEach((el, index) => {
        if (ts.isSpreadElement(el)) {
          reader.problem(el, "spread entries are not allowed in `templates`; list each defineTemplate({ ... })");
          return;
        }
        const obj = reader.objectOf(el, "template");
        if (!obj) return;
        const name = reader.literal(obj, "name", "template");
        if (name === null) return;
        const line = lineOf(reader.src, el);
        if (name.includes("/")) {
          reader.problem(el, `template name "${name}" must not contain a slash; the key is <folder>.<name>`);
          return;
        }
        const component = reader.property(obj, "component");
        let local: string | null = null;
        if (component && ts.isShorthandPropertyAssignment(component)) local = component.name.text;
        if (component && ts.isPropertyAssignment(component)) {
          const value = unwrap(component.initializer);
          if (ts.isIdentifier(value)) local = value.text;
        }
        const spec = local ? reader.importOf(local) : null;
        if (!spec) {
          reader.problem(el, `template "${name}": \`component\` must be a component imported from its own file`);
          return;
        }
        const basename = path.basename(spec).replace(/\.(tsx|ts|jsx|js)$/, "");
        const kebab = name.replace(/_/g, "-");
        if (kebab !== basename) {
          reader.problem(el, `template name "${name}" does not match its file "${basename}" (expected the file ${kebab}.tsx)`);
          return;
        }
        entries.push({ module: folder, rel, line, index, key: `${folder}.${name}`, extra: {} });
      });
    }
    problems.push(...reader.problems);
  }
  checkDuplicates(entries, "template", problems);
  return entries;
}

function templatesFile(entries: Entry[]): string {
  const sorted = [...entries].sort(byKey);
  return file(!entries.length, moduleImports(entries, "templates", "index", "."), [
    ...objectLiteral("TEMPLATE_REGISTRY", sorted.map((e) => [e.key, at(e, "templates")])),
    "",
    sorted.length
      ? `export const TEMPLATE_KEYS = [${sorted.map((e) => q(e.key)).join(", ")}] as const;`
      : "export const TEMPLATE_KEYS = [] as const;",
  ]);
}

/** `<m>.ts` then `<m>.views.ts` (only when it exists) for every schema file except `_shared.ts`. */
function collectSchema(root: string): string[] {
  const files = new Set(listFiles(path.join(root, SCHEMA_DIR)));
  const bases = sortStrings(
    [...files]
      .map((f) => /^([a-z][a-z0-9_-]*?)(\.views)?\.ts$/.exec(f)?.[1])
      .filter((b): b is string => !!b && b !== "index" && !b.endsWith(".test")),
  );
  const out: string[] = [];
  for (const b of bases) {
    if (files.has(`${b}.ts`)) out.push(b);
    if (files.has(`${b}.views.ts`)) out.push(`${b}.views`);
  }
  return out;
}

/** `packages/db/src/seed/<m>.ts` (module ids only) exporting `seed`. */
function collectDbSeeds(root: string, problems: string[]): { module: string; after: string[] }[] {
  const out: { module: string; after: string[] }[] = [];
  const ids = new Set<string>(MODULE_IDS);
  for (const f of listFiles(path.join(root, DB_SEED_DIR))) {
    const m = f.replace(/\.ts$/, "");
    if (!f.endsWith(".ts") || !ids.has(m)) continue;
    const reader = new Reader(readSource(root, `${DB_SEED_DIR}/${f}`));
    const seed = readSingle(reader, "seed", "default seed", true);
    if (seed) out.push({ module: m, after: seed.after });
    problems.push(...reader.problems);
  }
  return out;
}

/** `packages/core/src/i18n/messages/<locale>/<m>.json`. */
function collectMessages(root: string): { locale: string; module: string }[] {
  const out: { locale: string; module: string }[] = [];
  for (const locale of listDirs(path.join(root, MESSAGES_DIR))) {
    for (const f of listFiles(path.join(root, MESSAGES_DIR, locale))) {
      if (f.endsWith(".json")) out.push({ locale, module: f.replace(/\.json$/, "") });
    }
  }
  return out;
}

function messagesFile(entries: { locale: string; module: string }[]): string {
  const locales = sortStrings(entries.map((e) => e.locale));
  const modules = sortStrings(entries.map((e) => e.module));
  const imports = entries.map((e) => `import ${ident(e.locale, e.module)} from ${q(`./${e.locale}/${e.module}.json`)};`);
  const body = [
    "/** A catalogue: nested objects whose leaves are ICU message strings. */",
    "export type MessageTree = { readonly [key: string]: string | MessageTree };",
    "",
    `export const MESSAGE_LOCALES = [${locales.map(q).join(", ")}] as const;`,
    `export const MESSAGE_MODULES = [${modules.map(q).join(", ")}] as const;`,
    "",
    "export const MESSAGES: Readonly<Record<string, Readonly<Record<string, MessageTree>>>> = {",
    ...locales.map(
      (l) =>
        `  ${q(l)}: { ${entries
          .filter((e) => e.locale === l)
          .map((e) => `${q(e.module)}: ${ident(e.locale, e.module)}`)
          .join(", ")} },`,
    ),
    "};",
  ];
  return file(!entries.length, imports, body);
}

