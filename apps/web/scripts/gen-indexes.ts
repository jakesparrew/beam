type Source = { file: string; rel: string; sf: ts.SourceFile };

/** One registry entry found in a facade file. */
export type Entry = {
  module: string;
  rel: string;
  line: number;
  /** Position in the exported array (or the property name for records). */
  index: number;
  key: string;
  /** Extra literal properties read for some registries (`area`, component basename, `after`). */
  extra: Record<string, string | string[]>;
};

function readSource(root: string, rel: string): Source {
  const file = path.join(root, rel);
  const text = fs.readFileSync(file, "utf8");
  const kind = file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  return { file, rel, sf: ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind) };
}

function lineOf(src: Source, node: ts.Node): number {
  return src.sf.getLineAndCharacterOfPosition(node.getStart(src.sf)).line + 1;
}

function where(src: Source, node: ts.Node): string {
  return `${src.rel}:${lineOf(src, node)}`;
}

/** Strips `as const`, `satisfies T`, `<T>x` and parentheses. */
function unwrap(node: ts.Expression): ts.Expression {
  let n = node;
  while (
    ts.isAsExpression(n) ||
    ts.isSatisfiesExpression(n) ||
    ts.isParenthesizedExpression(n) ||
    ts.isTypeAssertionExpression(n) ||
    ts.isNonNullExpression(n)
  ) {
    n = n.expression;
  }
  return n;
}

/** Top-level `const name = init` declarations of the file (exported or not). */
function topLevelConsts(src: Source): Map<string, { init: ts.Expression; exported: boolean }> {
  const out = new Map<string, { init: ts.Expression; exported: boolean }>();
  for (const stmt of src.sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue;
    const exported = !!stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    for (const decl of stmt.declarationList.declarations) {
      if (ts.isIdentifier(decl.name) && decl.initializer) {
        out.set(decl.name.text, { init: decl.initializer, exported });
      }
    }
  }
  return out;
}

/** Local names bound by import declarations, mapped to their module specifier. */
function importedNames(src: Source): Map<string, string> {
  const out = new Map<string, string>();
  for (const stmt of src.sf.statements) {
    if (!ts.isImportDeclaration(stmt) || !ts.isStringLiteral(stmt.moduleSpecifier)) continue;
    const spec = stmt.moduleSpecifier.text;
    const clause = stmt.importClause;
    if (!clause) continue;
    if (clause.name) out.set(clause.name.text, spec);
    const bindings = clause.namedBindings;
    if (bindings && ts.isNamedImports(bindings)) for (const el of bindings.elements) out.set(el.name.text, spec);
    if (bindings && ts.isNamespaceImport(bindings)) out.set(bindings.name.text, spec);
  }
  return out;
}

function isStringish(node: ts.Expression): node is ts.StringLiteral | ts.NoSubstitutionTemplateLiteral {
  return ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node);
}

function propName(name: ts.PropertyName): string | null {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
  if (ts.isNoSubstitutionTemplateLiteral(name)) return name.text;
  return null;
}

class Reader {
  readonly problems: string[] = [];
  private readonly consts: Map<string, { init: ts.Expression; exported: boolean }>;
  private readonly imports: Map<string, string>;

  constructor(readonly src: Source) {
    this.consts = topLevelConsts(src);
    this.imports = importedNames(src);
  }

  problem(node: ts.Node, message: string): void {
    this.problems.push(`${where(this.src, node)}: ${message}`);
  }

  /** The initializer of `export const <name>`, or null when the file does not export it. */
  exported(name: string): ts.Expression | null {
    const found = this.consts.get(name);
    return found?.exported ? unwrap(found.init) : null;
  }

  /** Resolves an entry to its object literal: `{...}`, `fn({...})` or a same-file const. */
  objectOf(node: ts.Expression, what: string, depth = 0): ts.ObjectLiteralExpression | null {
    const n = unwrap(node);
    if (ts.isObjectLiteralExpression(n)) return n;
    if (ts.isCallExpression(n) && n.arguments[0]) {
      const arg = unwrap(n.arguments[0]);
      if (ts.isObjectLiteralExpression(arg)) return arg;
    }
    if (ts.isIdentifier(n) && depth < 5) {
      const local = this.consts.get(n.text);
      if (local) return this.objectOf(local.init, what, depth + 1);
      if (this.imports.has(n.text)) {
        this.problem(n, `${what} \`${n.text}\` is imported; declare the registration in this facade file with literal keys (only implementations may be imported)`);
        return null;
      }
    }
    this.problem(n, `${what} must be an object literal or a define*({ ... }) call`);
    return null;
  }

  /** The property `name` of an object literal (property assignment or shorthand). */
  property(obj: ts.ObjectLiteralExpression, name: string): ts.ObjectLiteralElementLike | undefined {
    return obj.properties.find((p) => p.name !== undefined && propName(p.name) === name);
  }

  /** A required string-literal property. */
  literal(obj: ts.ObjectLiteralExpression, name: string, what: string): string | null {
    const prop = this.property(obj, name);
    if (!prop) {
      this.problem(obj, `${what} has no \`${name}\` property`);
      return null;
    }
    if (ts.isPropertyAssignment(prop)) {
      const value = unwrap(prop.initializer);
      if (isStringish(value)) return value.text;
    }
    this.problem(prop, `registry values must be string literals (\`${name}\` of ${what})`);
    return null;
  }

  /** An optional array of string literals (`after: ['crm']`). */
  literalArray(obj: ts.ObjectLiteralExpression, name: string, what: string): string[] {
    const prop = this.property(obj, name);
    if (!prop) return [];
    if (ts.isPropertyAssignment(prop)) {
      const value = unwrap(prop.initializer);
      if (ts.isArrayLiteralExpression(value)) {
        const out: string[] = [];
        for (const el of value.elements) {
          const v = unwrap(el);
          if (isStringish(v)) out.push(v.text);
          else this.problem(el, `registry values must be string literals (\`${name}\` of ${what})`);
        }
        return out;
      }
    }
    this.problem(prop, `\`${name}\` of ${what} must be an array of string literals`);
    return [];
  }

  /** The module specifier an identifier was imported from, or null. */
  importOf(name: string): string | null {
    return this.imports.get(name) ?? null;
  }
}

