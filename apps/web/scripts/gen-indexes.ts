/** Joins a file body under the header; files without entries start with `export {};`. */
function file(empty: boolean, imports: string[], body: string[]): string {
  const lines = [HEADER];
  if (empty) lines.push("export {};");
  if (imports.length) lines.push(...imports);
  lines.push("", ...body);
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

function objectLiteral(name: string, rows: [string, string][], suffix = " as const"): string[] {
  if (!rows.length) return [`export const ${name} = {}${suffix};`];
  return [`export const ${name} = {`, ...rows.map(([k, v]) => `  ${q(k)}: ${v},`), `}${suffix};`];
}

function union(name: string, values: string[]): string[] {
  if (!values.length) return [`export type ${name} = never;`];
  return [`export type ${name} =`, ...values.map((v, i) => `  | ${q(v)}${i === values.length - 1 ? ";" : ""}`)];
}

/** Imports `exportName` from each module that has entries, aliased `<module>_<exportName>`. */
function moduleImports(entries: { module: string }[], exportName: string, facade: string, base = "../modules"): string[] {
  return sortStrings(entries.map((e) => e.module)).map(
    (m) => `import { ${exportName} as ${ident(m, exportName)} } from ${q(`${base}/${m}/${facade}`)};`,
  );
}

const at = (e: Entry, exportName: string) => `${ident(e.module, exportName)}[${e.index}]!`;

/** A record keyed by entry key pointing at the array element, plus a sorted values list. */
function keyedFile(entries: Entry[], spec: ListSpec, recordName: string, listName: string | null, valueOf?: (e: Entry) => string): string {
  const sorted = [...entries].sort(byKey);
  const rows: [string, string][] = sorted.map((e) => [e.key, valueOf ? valueOf(e) : at(e, spec.exportName)]);
  const body = objectLiteral(recordName, rows);
  if (listName) body.push(`export const ${listName} = Object.values(${recordName});`);
  return file(!entries.length, moduleImports(entries, spec.exportName, spec.file), body);
}

