/**
 * `pnpm gen:indexes`: writes every generated registry and index of the monorepo.
 *
 * It reads the per-module facade files statically with the TypeScript compiler API and
 * never imports module code, so it needs no environment and runs no side effects.
 * Registry keys (`kind`, `key`, `name`, `permission`, `provider`, `area`, `after`) must
 * be string literals in the facade file itself; only implementations may be imported.
 * Output is sorted and byte-stable; a file is rewritten only when its content changed.
 * Any problem (a duplicate key, a non-literal key) fails the run and writes nothing.
 *
 * The facade formats are documented in docs/plan/conventions.md ("Registries").
 */
