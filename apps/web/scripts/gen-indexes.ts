/** Writes the outputs that changed; returns the relative paths written. */
export function writeOutputs(root: string, outputs: Record<string, string>): string[] {
  const written: string[] = [];
  for (const rel of Object.keys(outputs).sort()) {
    const target = path.join(root, rel);
    const content = outputs[rel]!;
    if (fs.existsSync(target) && fs.readFileSync(target, "utf8") === content) continue;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
    written.push(rel);
  }
  return written;
}

export function main(root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..")): number {
  const started = Date.now();
  try {
    const outputs = generate(root);
    const written = writeOutputs(root, outputs);
    const total = Object.keys(outputs).length;
    console.log(`gen:indexes: ${written.length} of ${total} files written in ${Date.now() - started} ms`);
    return 0;
  } catch (error) {
    if (error instanceof GenIndexesError) {
      console.error(error.message);
      return 1;
    }
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main();
}
