/**
 * `pnpm db:append-only`: writes `src/sql/0002_append_only.sql` from `APPEND_ONLY_TABLES`
 * (PL-23a). `--check` exits 1 when the committed file differs from the generated content.
 * `--out <path>` writes (or checks) another file; tests use it with a fixture list.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { APPEND_ONLY_TABLES } from "../src/schema/_shared";

export const APPEND_ONLY_SQL_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/sql/0002_append_only.sql",
);

/** Wraps the table names into lines of at most ~90 characters, five spaces of indent. */
function tableArray(tables: readonly string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const [i, t] of tables.entries()) {
    const item = `'${t}'${i < tables.length - 1 ? "," : ""}`;
    if (line && line.length + 1 + item.length > 88) {
      lines.push(line);
      line = item;
    } else {
      line = line ? `${line} ${item}` : item;
    }
  }
  if (line) lines.push(line);
  return lines.map((l) => `    ${l}`).join("\n");
}

/** The full content of `0002_append_only.sql` for a table list. */
export function appendOnlySql(
  tables: readonly string[] = APPEND_ONLY_TABLES,
): string {
  for (const t of tables) {
    if (!/^[a-z_][a-z0-9_]*$/.test(t))
      throw new Error(`append-only: invalid table name "${t}"`);
  }
  return `-- GENERATED by pnpm db:append-only from APPEND_ONLY_TABLES. Do not edit.
create or replace function reject_update_delete() returns trigger
language plpgsql as $$
begin
  if coalesce(current_setting('beam.allow_rewrite', true), '') = 'on' then
    if tg_level = 'STATEMENT' then return null; end if;
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;
  raise exception 'append-only table %: % is not allowed', tg_table_name, tg_op
    using errcode = '55000', hint = 'Facts are insert-only. Erasure and retention use SET LOCAL beam.allow_rewrite = ''on''.';
end
$$;

create or replace function beam_protect_append_only() returns integer
language plpgsql as $$
declare
  t text;
  added integer := 0;
begin
  foreach t in array array[
${tableArray(tables)}
  ] loop
    if to_regclass('public.' || t) is not null
       and not exists (select 1 from pg_trigger
                       where tgrelid = to_regclass('public.' || t) and tgname = t || '_append_only') then
      execute format('create trigger %I before update or delete on public.%I for each row execute function reject_update_delete()', t || '_append_only', t);
      execute format('create trigger %I before truncate on public.%I for each statement execute function reject_update_delete()', t || '_append_only_truncate', t);
      added := added + 1;
    end if;
  end loop;
  return added;
end
$$;

select beam_protect_append_only();
`;
}

/** CLI. Returns the exit code. */
export function main(
  argv: string[] = process.argv.slice(2),
  tables: readonly string[] = APPEND_ONLY_TABLES,
): number {
  const check = argv.includes("--check");
  const outIndex = argv.indexOf("--out");
  const target =
    outIndex >= 0 && argv[outIndex + 1]
      ? path.resolve(argv[outIndex + 1]!)
      : APPEND_ONLY_SQL_PATH;
  const content = appendOnlySql(tables);
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (check) {
    if (current === content) {
      console.log(
        `db:append-only: ${path.basename(target)} is up to date (${tables.length} tables).`,
      );
      return 0;
    }
    console.error(
      `db:append-only: ${target} differs from APPEND_ONLY_TABLES. Run: pnpm db:append-only`,
    );
    return 1;
  }
  if (current !== content) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(
    `db:append-only: wrote ${path.basename(target)} (${tables.length} tables).`,
  );
  return 0;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  process.exitCode = main();
}
