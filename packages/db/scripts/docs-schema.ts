/**
 * `pnpm docs:schema` (PL-91): writes `docs/handbook/data-model.generated.md` from the Drizzle
 * schema with `getTableConfig`: per owning module its enums, tables, columns (type, null,
 * default, primary key, unique, foreign key), APPEND, IMMUTABLE and sensitive markings, and its
 * views. Output is sorted and byte-stable. `--check` exits 1 when the file differs;
 * `--out <path>` writes (or checks) another file.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { is, SQL } from "drizzle-orm";
import { toSnakeCase } from "drizzle-orm/casing";
import {
  getTableConfig,
  getViewConfig,
  isPgEnum,
  PgDialect,
  PgTable,
  PgView,
  type PgColumn,
} from "drizzle-orm/pg-core";
import {
  APPEND_ONLY_TABLES,
  IMMUTABLE_TABLES,
  SENSITIVE_COLUMNS,
} from "../src/schema/_shared";

const PACKAGE_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const SCHEMA_DIR = path.join(PACKAGE_DIR, "src/schema");
export const DOCS_SCHEMA_PATH = path.resolve(
  PACKAGE_DIR,
  "../../docs/handbook/data-model.generated.md",
);

/** One module's schema exports (`<m>.ts` and `<m>.views.ts` merged). */
export type SchemaModule = { module: string; exports: Record<string, unknown> };
export type Markings = {
  appendOnly: readonly string[];
  immutable: readonly string[];
  sensitive: readonly { table: string; column: string; keyColumn: string }[];
};

const dialect = new PgDialect({ casing: "snake_case" });
const columnName = (c: PgColumn) =>
  c.keyAsName ? toSnakeCase(c.name) : c.name;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function defaultOf(c: PgColumn): string {
  if (c.default !== undefined) {
    if (is(c.default, SQL)) return `\`${dialect.sqlToQuery(c.default).sql}\``;
    return `\`${JSON.stringify(c.default)}\``;
  }
  if (c.defaultFn) return "set by code";
  const generated = (c as { generatedIdentity?: { type?: string } })
    .generatedIdentity;
  if (generated?.type) return `identity (${generated.type})`;
  return "";
}

/** The Markdown document for the given modules (sorted by module id, then name). */
export function schemaDoc(modules: SchemaModule[], markings: Markings): string {
  const sensitive = new Map(
    markings.sensitive.map((s) => [`${s.table}.${s.column}`, s.keyColumn]),
  );
  const out: string[] = [
    "<!-- GENERATED by pnpm docs:schema from packages/db/src/schema. Do not edit. -->",
    "",
    "# Data model (generated)",
    "",
    "Markings: **APPEND** = insert-only (trigger `reject_update_delete()`), **IMMUTABLE** = published rows are never edited, **SENSITIVE** = special-category data, read only through `readSensitive()`.",
    "",
  ];
  for (const { module, exports } of [...modules].sort((a, b) =>
    a.module.localeCompare(b.module),
  )) {
    const values = Object.values(exports);
    const tables = values
      .filter((v): v is PgTable => is(v, PgTable))
      .map((t) => getTableConfig(t));
    const enums = values.filter(isPgEnum);
    const views = values
      .filter((v): v is PgView => is(v, PgView))
      .map((v) => getViewConfig(v).name);
    if (!tables.length && !enums.length && !views.length) continue;
    out.push(`## ${module}`, "");
    if (enums.length) {
      out.push("### Enums", "", "| Enum | Values |", "| --- | --- |");
      for (const e of [...enums].sort((a, b) =>
        a.enumName.localeCompare(b.enumName),
      )) {
        out.push(
          `| \`${e.enumName}\` | ${e.enumValues.map((v) => `\`${v}\``).join(", ")} |`,
        );
      }
      out.push("");
    }
    for (const t of [...tables].sort((a, b) => a.name.localeCompare(b.name))) {
      const flags = [
        markings.appendOnly.includes(t.name) ? "APPEND" : "",
        markings.immutable.includes(t.name) ? "IMMUTABLE" : "",
      ].filter(Boolean);
      out.push(
        `### \`${t.name}\`${flags.length ? ` (${flags.join(", ")})` : ""}`,
        "",
      );
      const fks = new Map<string, string>();
      for (const fk of t.foreignKeys) {
        const ref = fk.reference();
        const target = getTableConfig(ref.foreignTable).name;
        ref.columns.forEach((c, i) => {
          const fc = ref.foreignColumns[i];
          fks.set(
            columnName(c),
            `${target}.${fc ? columnName(fc) : "?"}${fk.onDelete ? ` on delete ${fk.onDelete}` : ""}`,
          );
        });
      }
      const pk = new Set(
        t.primaryKeys.flatMap((p) => p.columns.map(columnName)),
      );
      out.push(
        "| Column | Type | Null | Default | Key | References | Marking |",
        "| --- | --- | --- | --- | --- | --- | --- |",
      );
      for (const c of t.columns) {
        const name = columnName(c);
        const key =
          c.primary || pk.has(name) ? "PK" : c.isUnique ? "unique" : "";
        const keyColumn = sensitive.get(`${t.name}.${name}`);
        out.push(
          `| \`${name}\` | ${cell(c.getSQLType())} | ${c.notNull ? "no" : "yes"} | ${cell(defaultOf(c))} | ${key} | ${fks.get(name) ?? ""} | ${keyColumn ? `SENSITIVE (key ${keyColumn})` : ""} |`,
        );
      }
      const extras = [
        ...t.indexes.map(
          (i) =>
            `${i.config.unique ? "unique index" : "index"} \`${i.config.name ?? ""}\``,
        ),
        ...t.checks.map((c) => `check \`${c.name}\``),
      ].sort();
      if (extras.length) out.push("", extras.join("; "));
      out.push("");
    }
    if (views.length) {
      out.push(
        "### Views",
        "",
        ...[...views].sort().map((v) => `- \`${v}\``),
        "",
      );
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/** Imports every `<m>.ts` and `<m>.views.ts` of `src/schema` (not `_shared.ts` or the index). */
export async function loadSchemaModules(
  dir = SCHEMA_DIR,
): Promise<SchemaModule[]> {
  const byModule = new Map<string, Record<string, unknown>>();
  for (const f of readdirSync(dir).sort()) {
    const m = /^([a-z][a-z0-9_-]*?)(\.views)?\.ts$/.exec(f);
    if (!m || m[1] === "index" || f.endsWith(".test.ts")) continue;
    const mod = (await import(pathToFileURL(path.join(dir, f)).href)) as Record<
      string,
      unknown
    >;
    byModule.set(m[1]!, { ...byModule.get(m[1]!), ...mod });
  }
  return [...byModule].map(([module, exports]) => ({ module, exports }));
}

export const defaultMarkings = (): Markings => ({
  appendOnly: APPEND_ONLY_TABLES,
  immutable: IMMUTABLE_TABLES,
  sensitive: SENSITIVE_COLUMNS,
});

/** CLI. Returns the exit code. */
export async function main(
  argv: string[] = process.argv.slice(2),
  deps: {
    modules?: SchemaModule[];
    markings?: Markings;
    log?: (s: string) => void;
    error?: (s: string) => void;
  } = {},
): Promise<number> {
  const log = deps.log ?? console.log;
  const error = deps.error ?? console.error;
  const outAt = argv.indexOf("--out");
  const target =
    outAt >= 0 && argv[outAt + 1]
      ? path.resolve(argv[outAt + 1]!)
      : DOCS_SCHEMA_PATH;
  const content = schemaDoc(
    deps.modules ?? (await loadSchemaModules()),
    deps.markings ?? defaultMarkings(),
  );
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (argv.includes("--check")) {
    if (current === content) {
      log(`docs:schema: ${path.basename(target)} is up to date.`);
      return 0;
    }
    error(
      `docs:schema: ${target} differs from the schema. Run: pnpm docs:schema`,
    );
    return 1;
  }
  if (current !== content) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  log(`docs:schema: wrote ${target}`);
  return 0;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  void main().then((code) => {
    process.exitCode = code;
  });
}
