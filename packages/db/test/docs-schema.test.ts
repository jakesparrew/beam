import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { integer, pgEnum, pgTable, text, uuid } from "drizzle-orm/pg-core";
import { describe, expect, it } from "vitest";
import {
  defaultMarkings,
  loadSchemaModules,
  main,
  schemaDoc,
  type SchemaModule,
} from "../scripts/docs-schema";

const quiet = { log: () => undefined, error: () => undefined };

const fixtureEnum = pgEnum("fixture_items_state", ["open", "closed"]);
const fixtureV1 = pgTable("fixture_items", {
  id: uuid().primaryKey().defaultRandom(),
  state: fixtureEnum().notNull().default("open"),
  label: text().notNull(),
});
const fixtureV2 = pgTable("fixture_items", {
  id: uuid().primaryKey().defaultRandom(),
  state: fixtureEnum().notNull().default("open"),
  label: text().notNull(),
  sortOrder: integer().notNull().default(0),
});
const fixture = (table: unknown): SchemaModule[] => [
  { module: "fixture", exports: { fixtureEnum, table } },
];
const markings = { appendOnly: [], immutable: [], sensitive: [] };

describe("docs-schema", () => {
  it("gives byte-identical output on two runs over the real schema", async () => {
    const first = schemaDoc(await loadSchemaModules(), defaultMarkings());
    const second = schemaDoc(await loadSchemaModules(), defaultMarkings());
    expect(second).toBe(first);
    expect(first.startsWith("<!-- GENERATED by pnpm docs:schema")).toBe(true);
  });

  it("shows owning modules, APPEND, IMMUTABLE and sensitive markings, enums, keys and references", async () => {
    const doc = schemaDoc(await loadSchemaModules(), defaultMarkings());
    expect(doc).toContain("## platform");
    expect(doc).toContain("## crm");
    expect(doc).toContain("### `audit_log` (APPEND)");
    expect(doc).toContain("### `order_lines` (APPEND, IMMUTABLE)");
    expect(doc).toMatch(
      /\| `data` \| jsonb \| no \| .* \| SENSITIVE \(key data\.key_version\) \|/,
    );
    expect(doc).toContain("| `roles_key` |");
    expect(doc).toContain("persons.id on delete restrict");
    expect(doc).toContain("- `v_support_sla`");
    expect(doc).toContain("check `users_audience_shape_ck`");
    // snake_case column names, never the TypeScript property keys
    expect(doc).toContain("| `idempotency_key` |");
    expect(doc).not.toContain("idempotencyKey");
  });

  it("--check passes on a fresh file and fails after a fixture column is added", async () => {
    const out = path.join(
      mkdtempSync(path.join(tmpdir(), "platform-p2-docs-")),
      "data-model.generated.md",
    );
    expect(
      await main(["--out", out], {
        modules: fixture(fixtureV1),
        markings,
        ...quiet,
      }),
    ).toBe(0);
    expect(
      await main(["--check", "--out", out], {
        modules: fixture(fixtureV1),
        markings,
        ...quiet,
      }),
    ).toBe(0);
    expect(
      await main(["--check", "--out", out], {
        modules: fixture(fixtureV2),
        markings,
        ...quiet,
      }),
    ).toBe(1);
    const doc = schemaDoc(fixture(fixtureV2), markings);
    expect(doc).toContain("| `sort_order` | integer | no | `0` |");
    expect(doc).toContain("| `fixture_items_state` | `open`, `closed` |");
  });
});
