/** Renders a nav icon: a lucide name from `NAV_ICONS`, or any element passed as is. */
export function NavIcon({
  icon,
  className,
}: {
  icon?: string | ReactNode;
  className?: string;
}) {
  if (icon === undefined || icon === null || icon === false) return null;
  if (typeof icon === "string") {
    const Icon = NAV_ICONS[icon] ?? CircleIcon;
    return <Icon className={className ?? "size-4"} aria-hidden />;
  }
  return (
    <span aria-hidden="true" className="inline-flex">
      {icon}
    </span>
  );
}
